import { beforeEach, describe, expect, it, vi } from 'vitest'
import { studioAPI, type StudioTask } from '../api'
import { modelIdentity, workspaceAPI } from '../workspaceAPI'
import { cacheStudioModels, cachedStudioModels } from '../cache'

vi.mock('../api', () => ({ studioAPI: vi.fn() }))
const model = (id: string, provider = 'fixture') => ({ id, provider, object: 'model' })
const task = (id: string) => ({ id: `${id}/one`, job: { id, model: 'image', provider: 'fixture', status: 'completed' }, item: { custom_id: 'one', image_count: 1 } }) as StudioTask
function client(models = [model('image')]) {
  return { models: vi.fn(async () => models), tasks: vi.fn(async (_cursor = '') => ({ tasks: [] as StudioTask[], itemContinuations: [], nextCursor: null as string | null })), items: vi.fn(), image: vi.fn(), thumbnail: vi.fn(), cancel: vi.fn(), refreshPending: vi.fn(async (tasks: StudioTask[]) => tasks), submit: vi.fn() }
}
beforeEach(() => { vi.clearAllMocks(); sessionStorage.clear() })
describe('model-directed workspace', () => {
  it('shows available works before a slow history channel completes, retaining its cursor', async () => {
    const fast = client(), slow = client(), a = task('fast'), b = task('slow')
    fast.tasks.mockResolvedValue({ tasks: [a], itemContinuations: [], nextCursor: null })
    fast.thumbnail.mockResolvedValue(new Blob(['cover']))
    let finish!: (page: Awaited<ReturnType<typeof slow.tasks>>) => void
    slow.tasks.mockImplementation(() => new Promise(resolve => { finish = resolve }))
    vi.mocked(studioAPI).mockImplementation(key => key === 1 ? fast : slow)
    const api = workspaceAPI([1, 2], new AbortController().signal)
    const update = vi.fn()
    const pending = api.tasks('', undefined, update)
    await vi.waitFor(() => expect(update).toHaveBeenCalledWith([a]))
    await api.thumbnail(a)
    expect(fast.thumbnail).toHaveBeenCalledWith(a, expect.any(AbortSignal))
    finish({ tasks: [b], itemContinuations: [], nextCursor: 'next-slow' })
    const page = await pending
    expect(page.tasks).toEqual([a, b])
    expect(JSON.parse(page.nextCursor!)).toEqual({ 1: null, 2: 'next-slow' })
  })
  it('publishes each channel without waiting for a slower catalogue', async () => {
    const fast = client([model('fast')]), slow = client()
    let finish!: (models: ReturnType<typeof model>[]) => void
    slow.models.mockImplementation(() => new Promise(resolve => { finish = resolve }))
    vi.mocked(studioAPI).mockImplementation(key => key === 1 ? fast : slow)
    const api = workspaceAPI([1, 2], new AbortController().signal)
    const update = vi.fn()
    const pending = api.models(update)
    await vi.waitFor(() => expect(update).toHaveBeenCalledWith([model('fast')]))
    finish([model('slow')])
    expect(await pending).toEqual([model('fast'), model('slow')])
  })
  it('shows cached models immediately but never authorizes a POST from stale admission', async () => {
    cacheStudioModels(1, 1, [model('old')])
    const source = client()
    source.models.mockRejectedValue({ status: 403 })
    vi.mocked(studioAPI).mockReturnValue(source)
    const api = workspaceAPI([1], new AbortController().signal, { userId: 1, modelKeys: [1], historyKeys: [] })
    expect(api.cachedModels()).toEqual([model('old')])
    await expect(api.submit({ provider: 'fixture', model: 'old', items: [] }, 'attempt')).rejects.toThrow()
    expect(source.submit).not.toHaveBeenCalled()
    expect(api.cachedModels()).toEqual([])
    expect(cachedStudioModels(1, 1)).toBeUndefined()
  })
  it('does not let an older refresh overwrite a newer cached directory', async () => {
    const source = client()
    let finish!: (models: ReturnType<typeof model>[]) => void
    source.models.mockImplementationOnce(() => new Promise(resolve => { finish = resolve })).mockResolvedValueOnce([model('new')])
    vi.mocked(studioAPI).mockReturnValue(source)
    const api = workspaceAPI([1], new AbortController().signal, { userId: 1, modelKeys: [1], historyKeys: [] })
    const old = api.models()
    api.refreshDirectory()
    await api.models()
    finish([model('old')])
    await old
    expect(api.cachedModels()).toEqual([model('new')])
    expect(cachedStudioModels(1, 1)).toEqual([model('new')])
  })
  it('keeps cached metadata on a transient read failure while blocking unverified generation', async () => {
    cacheStudioModels(1, 1, [model('old')])
    const source = client()
    source.models.mockRejectedValue({ status: 503 })
    vi.mocked(studioAPI).mockReturnValue(source)
    const api = workspaceAPI([1], new AbortController().signal, { userId: 1, modelKeys: [1], historyKeys: [] })
    expect(await api.models()).toEqual([model('old')])
    expect(api.warnings().join()).toContain('最近记录')
    await expect(api.submit({ provider: 'fixture', model: 'old', items: [] }, 'attempt')).rejects.toThrow()
    expect(source.submit).not.toHaveBeenCalled()
  })
  it('discovers eligible model keys and reads historical keys independently', async () => {
    // Given an image key, a historical disabled-group key and an unrelated key.
    const generation = client(), history = client(), unrelated = client()
    const sources = new Map([[1, generation], [2, history], [3, unrelated]])
    generation.submit.mockResolvedValue(task('new').job)
    vi.mocked(studioAPI).mockImplementation(key => sources.get(key)!)
    const api = workspaceAPI([1, 2, 3], new AbortController().signal, { modelKeys: [1], historyKeys: [2] })
    // When the workspace loads its catalogue and first history page.
    await api.models()
    await api.tasks()
    // Then no irrelevant or empty-history requests are made.
    expect(generation.models).toHaveBeenCalledOnce()
    expect(history.tasks).toHaveBeenCalledOnce()
    expect(generation.tasks).not.toHaveBeenCalled()
    expect(history.models).not.toHaveBeenCalled()
    expect(unrelated.models).not.toHaveBeenCalled()
    expect(unrelated.tasks).not.toHaveBeenCalled()
    await api.submit({ model: 'image', provider: 'fixture', items: [] }, 'new-attempt')
    await api.tasks()
    expect(generation.tasks).toHaveBeenCalledOnce()
  })
  it('loads other covers while a cold preview remains pending with bounded concurrency', async () => {
    // Given five visible covers, including a slow first cover.
    const source = client(), tasks = Array.from({ length: 5 }, (_, index) => task(String(index)))
    source.tasks.mockResolvedValue({ tasks, itemContinuations: [], nextCursor: null })
    const release: (() => void)[] = []
    source.thumbnail.mockImplementation(() => new Promise<Blob>(resolve => { release.push(() => resolve(new Blob(['cover']))) }))
    vi.mocked(studioAPI).mockReturnValue(source)
    const api = workspaceAPI([1], new AbortController().signal)
    await api.tasks()
    // When covers enter the shared preview queue.
    const pending = tasks.map(item => api.thumbnail(item))
    // Then three reads can progress and completing a later cover starts another.
    await vi.waitFor(() => expect(source.thumbnail).toHaveBeenCalledTimes(3))
    release[1]?.()
    await vi.waitFor(() => expect(source.thumbnail).toHaveBeenCalledTimes(4))
    release[2]?.()
    await vi.waitFor(() => expect(source.thumbnail).toHaveBeenCalledTimes(5))
    for (const finish of release) finish()
    await Promise.all(pending)
  })
  it('loads history while catalogue discovery is still unresolved', async () => {
    const source = client()
    source.models.mockImplementation(() => new Promise(() => {}))
    vi.mocked(studioAPI).mockReturnValue(source)
    const api = workspaceAPI([1], new AbortController().signal)
    void api.models()
    await api.tasks()
    expect(source.tasks).toHaveBeenCalledOnce()
  })
  it('deduplicates model routes while retaining provider identity and ignores non-image admission', async () => {
    const first = client(), duplicate = client(), second = client([model('image', 'other')]), text = client()
    text.models.mockRejectedValue({ status: 403 })
    const clients = new Map([[1, first], [2, duplicate], [3, second], [4, text]])
    vi.mocked(studioAPI).mockImplementation(key => clients.get(key)!)
    const api = workspaceAPI([4, 2, 3, 1], new AbortController().signal)
    expect((await api.models()).map(modelIdentity)).toEqual(['fixture:image', 'other:image'])
    expect(api.warnings()).toEqual([])
  })
  it('keeps independent history cursors and routes assets and cancellation to their original owner', async () => {
    const first = client(), second = client()
    const a = task('a'), b = task('b'), c = task('c')
    first.tasks.mockResolvedValueOnce({ tasks: [a], itemContinuations: [], nextCursor: '12' }).mockResolvedValueOnce({ tasks: [c], itemContinuations: [], nextCursor: null })
    second.tasks.mockResolvedValue({ tasks: [b], itemContinuations: [], nextCursor: null })
    vi.mocked(studioAPI).mockImplementation(key => key === 10 ? first : second)
    const api = workspaceAPI([10, 20], new AbortController().signal)
    const page = await api.tasks()
    expect(page.tasks.map(task => task.id).sort()).toEqual(['a/one', 'b/one'])
    await api.image(b, 0); await api.cancel(a)
    expect(second.image).toHaveBeenCalledWith(b, 0)
    expect(first.cancel).toHaveBeenCalledWith(a)
    await api.tasks(page.nextCursor!)
    expect(first.tasks).toHaveBeenLastCalledWith('12')
    expect(second.tasks).toHaveBeenCalledOnce()
  })
  it('pins an uncertain POST to the same key and never rotates to a newly preferred route', async () => {
    const first = client(), second = client()
    first.submit.mockRejectedValue(new Error('timeout'))
    vi.mocked(studioAPI).mockImplementation(key => key === 10 ? first : second)
    const api = workspaceAPI([10, 20], new AbortController().signal)
    const body = { model: 'image', provider: 'fixture', items: [{ custom_id: 'one', prompt: 'boat' }] }
    await expect(api.submit(body, 'same-attempt')).rejects.toThrow('timeout')
    first.models.mockResolvedValue([]); api.refreshDirectory()
    await api.models()
    await expect(api.submit(body, 'same-attempt')).rejects.toThrow('timeout')
    expect(first.submit).toHaveBeenCalledTimes(2)
    expect(first.submit.mock.calls[1]?.[1]).toBe('same-attempt')
    expect(second.submit).not.toHaveBeenCalled()
  })
  it('retains an editing root on its own key and refuses cross-key continuation', async () => {
    const first = client(), second = client([model('muse')]), source = task('root')
    first.tasks.mockResolvedValue({ tasks: [source], itemContinuations: [], nextCursor: null })
    first.submit.mockResolvedValue(task('child').job)
    vi.mocked(studioAPI).mockImplementation(key => key === 10 ? first : second)
    const api = workspaceAPI([10, 20], new AbortController().signal)
    await api.tasks()
    expect(await api.canContinue(source, model('image'))).toBe(true)
    expect(await api.canContinue(source, model('muse'))).toBe(false)
    await expect(api.submit({ model: 'muse', provider: 'fixture', parent_batch_id: 'root', items: [] }, 'edit')).rejects.toThrow('原作品')
    expect(second.submit).not.toHaveBeenCalled()
    await api.submit({ model: 'image', provider: 'fixture', parent_batch_id: 'root', items: [] }, 'valid-edit')
    expect(first.submit).toHaveBeenCalledOnce()
  })
  it('serializes gallery and detail image reads across keys for the shared user download limit', async () => {
    const first = client(), second = client(), a = task('a'), b = task('b')
    const releases: (() => void)[] = []
    first.tasks.mockResolvedValue({ tasks: [a], itemContinuations: [], nextCursor: null })
    second.tasks.mockResolvedValue({ tasks: [b], itemContinuations: [], nextCursor: null })
    first.image.mockImplementation(() => new Promise<Blob>(resolve => { releases.push(() => resolve(new Blob(['a']))) }))
    second.image.mockResolvedValue(new Blob(['b']))
    vi.mocked(studioAPI).mockImplementation(key => key === 10 ? first : second)
    const api = workspaceAPI([10, 20], new AbortController().signal)
    await api.tasks()
    const firstRead = api.image(a), secondRead = api.image(b)
    await vi.waitFor(() => expect(first.image).toHaveBeenCalledOnce())
    expect(second.image).not.toHaveBeenCalled()
    expect(releases).toHaveLength(1)
    releases.shift()?.()
    await firstRead
    await expect(secondRead).resolves.toBeInstanceOf(Blob)
    expect(second.image).toHaveBeenCalledWith(b, 0)
  })
  it('continues queued image reads after an asset failure without retrying the failed read', async () => {
    const source = client(), a = task('a'), b = task('b')
    source.tasks.mockResolvedValue({ tasks: [a, b], itemContinuations: [], nextCursor: null })
    source.image.mockRejectedValueOnce(new Error('asset unavailable')).mockResolvedValueOnce(new Blob(['b']))
    vi.mocked(studioAPI).mockReturnValue(source)
    const api = workspaceAPI([10], new AbortController().signal)
    await api.tasks()
    const failed = api.image(a), next = api.image(b)
    await expect(failed).rejects.toThrow('asset unavailable')
    await expect(next).resolves.toBeInstanceOf(Blob)
    expect(source.image).toHaveBeenCalledTimes(2)
  })
  it('does not start a queued image read after the workspace is aborted', async () => {
    const source = client(), a = task('a'), b = task('b'), controller = new AbortController()
    const releases: (() => void)[] = []
    source.tasks.mockResolvedValue({ tasks: [a, b], itemContinuations: [], nextCursor: null })
    source.image.mockImplementation(() => new Promise<Blob>(resolve => { releases.push(() => resolve(new Blob())) }))
    vi.mocked(studioAPI).mockReturnValue(source)
    const api = workspaceAPI([10], controller.signal)
    await api.tasks()
    const first = api.image(a), queued = api.image(b)
    await vi.waitFor(() => expect(source.image).toHaveBeenCalledOnce())
    controller.abort()
    releases.shift()?.()
    await first
    await expect(queued).rejects.toMatchObject({ name: 'AbortError' })
    expect(source.image).toHaveBeenCalledOnce()
  })
  it('opens originals while a cover is preparing and skips cancelled queued covers', async () => {
    const source = client(), a = task('a'), b = task('b'), c = task('c'), d = task('d'), card = new AbortController()
    source.tasks.mockResolvedValue({ tasks: [a, b, c, d], itemContinuations: [], nextCursor: null })
    const finishes: ((blob: Blob) => void)[] = []
    source.thumbnail.mockImplementation(() => new Promise<Blob>(resolve => { finishes.push(resolve) }))
    source.image.mockResolvedValue(new Blob(['original']))
    vi.mocked(studioAPI).mockReturnValue(source)
    const api = workspaceAPI([10], new AbortController().signal)
    await api.tasks()
    const covers = [api.thumbnail(a), api.thumbnail(c), api.thumbnail(d)]
    const queued = api.thumbnail(b, card.signal)
    await vi.waitFor(() => expect(source.thumbnail).toHaveBeenCalledTimes(3))
    await expect(api.image(b)).resolves.toBeInstanceOf(Blob)
    card.abort()
    const cancelled = expect(queued).rejects.toMatchObject({ name: 'AbortError' })
    for (const finish of finishes) finish(new Blob(['cover']))
    await Promise.all(covers)
    await cancelled
    await api.thumbnail(a)
    expect(source.thumbnail).toHaveBeenCalledTimes(3)
    expect(source.image).toHaveBeenCalledWith(b, 0)
  })
})
